public class Loop {

    public static void main(String[] args) {
        
        int i= 1;// create a conter variable,name it i and start it at 1 
        while(i<=5){// repeat the loop while i is less than or equal to 5
            System.out.println(i);//display the current value of i to the screen
            i++;//increase i by 1 so the loop can eventually stop
            
        }
    }
}





